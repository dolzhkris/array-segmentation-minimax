#генерация всех разбиений массива a на k непустых подряд идущих отрезков
def gen_otr(a, k):
    n = len(a) #количество элементов в массиве

    def form_otr(start, parts_left, current):
        #start — текущая позиция в массиве, откуда начинается формирование отрезка
        #parts_left — сколько отрезков еще нужно сформировать
        #current — список уже сформированных отрезков
        if parts_left == 1:  #если остался только один отрезок, то он включает все оставшиеся элементы
            current.append(a[start:]) #добавляется остаток массива в текущее разбиение
            yield list(current) #возвращается копия текущего разбиения
            current.pop() #удаляется добавленный отрезок, чтобы попробовать другие варианты
            return 
        for i in range(start + 1, n - parts_left + 2):  #иначе пытаемся сформировать следующий отрезок
            current.append(a[start:i])  #добавляется отрезок в текущий список
            yield from form_otr(i, parts_left - 1, current) #рекурсивно строятся оставшиеся отрезки
            current.pop() #удаляется последний добавленный отрезок

    return form_otr(0, k, []) #запускается рекурсия с позиции 0, нужно k отрезков, текущий список пуст

#вывод всех разбиений и нахождение минимальной суммы
def print_var_and_find_min(a, k):
    min_max_sum = float('inf')  #минимально возможный максимум (изначально бесконечность)
    best_var = None #лучшее разбиение

    for variations in gen_otr(a, k): #перебираются все разбиения
        sums = [sum(var) for var in variations] #вычисляются суммы каждого отрезка
        max_sum = max(sums) #находится максимальная сумма среди отрезков
        #формируется красивый вывод
        var_str = " | ".join(f"[{', '.join(map(str, var))}]" for var in variations) 
        print(f"{var_str} → max = {max_sum}") #выводим разбиение и максимальную сумму
        if max_sum < min_max_sum: #если текущий максимум меньше найденного ранее
            min_max_sum = max_sum #обновляется минимальный максимум
            best_var = variations #обновляется лучшее разбиение

    print(f"\nРезультат минимального значения: {min_max_sum}.") #выводится минимальный максимум

n, k = map(int, input().split()) #ввод количества элементов и количества отрезков
a = list(map(int, input().split())) #ввод массива

print_var_and_find_min(a, k) #вызов функции для вывода разбиений и нахождения минимального максимума
